Subject: Statement of the FreeBSD Core Team Regarding the EU Cyber Resilience Act
The FreeBSD Foundation has long provided legal, financial, administrative, strategic, and operational support for the FreeBSD Project, and is well-positioned to engage with governmental authorities, industry participants, and other organizations on behalf of FreeBSD.

We support the FreeBSD Foundation in serving as an open-source software steward for matters related to the Cyber Resilience Act (CRA). This provides essential clarity for users, contributors, commercial adopters, regulators, and other stakeholders.
We also explicitly affirm that our recognition of the Foundation is inclusive. It is not intended to exclude or diminish the role of other organizations, enterprises, and downstream partners that invest heavily in FreeBSD, including those employing developers to maintain the project's security infrastructure. As regulatory definitions evolve and community contributions change, we recognize that these vital ecosystem participants may also independently qualify as stewards or fulfill other distinct roles within the CRA framework.

Warner Losh on behalf of The FreeBSD Core team on behalf of the FreeBSD Project.